"""Step 5: write Figures 1-12 to results/figures (PNG, 300 dpi)."""
import argparse
import json
import os

from intellinav3d import figures as F
from intellinav3d.config import load_config, parse_overrides
from intellinav3d.data.split import load_split
from intellinav3d.scene import Scene
from intellinav3d.tables import fid_of, mean_of, metric

ROOM_LABEL = {"bedroom": "Bedroom", "livingroom": "Living room", "diningroom": "Dining room"}


def fig5_from_model(cfg, test_scenes, out):
    try:
        import torch  # noqa: F401
        from intellinav3d import pipeline as PL
    except ImportError:
        print("Fig. 5 skipped: PyTorch not installed")
        return
    split = load_split(cfg.paths.split_file)
    stats = PL.prepare_stats(cfg, split)
    gat_ck = os.path.join(cfg.paths.runs_dir, "gat", PL.gat_key(cfg, 0), "gat.pt")
    ddpm_ck = os.path.join(cfg.paths.runs_dir, "ddpm", PL.ddpm_key(cfg, 0, True), "ddpm.pt")
    if not (os.path.exists(gat_ck) and os.path.exists(ddpm_ck)):
        print("Fig. 5 skipped: trained GAT/DDPM of seed 0 not found (run the main stage first)")
        return
    gat = PL.load_gat(cfg, gat_ck)
    model, diff = PL.load_ddpm(cfg, ddpm_ck, True)
    bed = [s for s in test_scenes if s.room_type == "bedroom"][:1] or test_scenes[:1]
    T = cfg.ddpm.timesteps
    steps = (T - 1, int(0.6 * T), int(0.3 * T), int(0.1 * T), 0)
    _, st = PL.generate_ddpm(cfg, model, diff, gat, bed, stats, 1, seed=0, batch=1, return_steps=steps)
    sid = bed[0].scene_id
    F.fig5({t + 1 if t else 0: s for t, s in st[sid].items()}, out,
           f"Layout generated by the trained DDPM at successive reverse steps (test room {sid})")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default=None)
    ap.add_argument("--set", nargs="*", default=[])
    ap.add_argument("--skip_fig5", action="store_true")
    a = ap.parse_args()
    cfg = load_config(a.config, parse_overrides(a.set))
    out = os.path.join(cfg.paths.results_dir, "figures")
    rp = os.path.join(cfg.paths.results_dir, "results.json")
    res = json.load(open(rp)) if os.path.exists(rp) else {}
    test_ids = load_split(cfg.paths.split_file)["test"] if os.path.exists(cfg.paths.split_file) else []
    test = [Scene.load(os.path.join(cfg.paths.scenes_dir, i + ".json")) for i in test_ids[:400]]
    if test:
        F.fig1(cfg, test, out)
    F.fig2(out)
    F.fig3(cfg, out)
    F.fig4(cfg, out)
    if not a.skip_fig5 and test:
        fig5_from_model(cfg, test, out)
    F.fig6(cfg, out)
    F.fig7(cfg, out)
    F.fig8(out)
    if test:
        ext = os.path.join(cfg.paths.runs_dir, "outputs", "external_methods")
        ours = os.path.join(cfg.paths.runs_dir, "outputs", "main", "full", "seed0", "scenes")
        methods = [("Ground truth", cfg.paths.scenes_dir)] + \
                  [(m, os.path.join(ext, m, "seed0", "scenes")) for m in ("ATISS", "DiffuScene", "Nav2Scene")] + \
                  [("IntelliNav3D", ours)]
        pick = []
        for rt in ("bedroom", "livingroom", "diningroom"):
            pick += [s.scene_id for s in test if s.room_type == rt][:2]
        F.fig_compare(cfg, pick[0::2] or test_ids[:3], methods, out, "Fig9_scene_completion.png",
                      "Scene results of ATISS, DiffuScene, Nav2Scene and IntelliNav3D on 3D-FRONT")
        F.fig_compare(cfg, pick[1::2] or test_ids[3:6], methods, out, "Fig10_rearrangement.png",
                      "Qualitative comparison of indoor scene re-arrangement results")
    ours_all = {"accessibility": mean_of(res, "main", "full", metric("all", "accessibility")),
                "objects_out_of_room": mean_of(res, "main", "full", metric("all", "objects_out_of_room")),
                "collision_rate": mean_of(res, "main", "full", metric("all", "collision_rate")),
                "fid": mean_of(res, "main", "full", fid_of("all"))}
    F.fig11(ours_all, out)
    by_room = {ROOM_LABEL[k]: {"out": mean_of(res, "main", "full", metric(k, "objects_out_of_room")),
                               "walk": mean_of(res, "main", "full", metric(k, "accessibility")),
                               "fid": mean_of(res, "main", "full", fid_of(k))} for k in ROOM_LABEL}
    F.fig12(by_room, out)
    print(f"figures written to {out}")


if __name__ == "__main__":
    main()
